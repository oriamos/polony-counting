import { chromium } from 'playwright-core';
import { server } from '../mock/server.mjs';
await new Promise((r) => server.listen(0, '127.0.0.1', r));
const BASE = `http://127.0.0.1:${server.address().port}`;
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1500, height: 900 } });
await p.goto(BASE);
await p.click('[data-testid=analysis-demo]');
await p.waitForTimeout(800);
await p.keyboard.press('h');
await p.click('[data-testid=queue-o-0002]');
await p.keyboard.press('Escape');
await p.waitForTimeout(400);
const box = await p.locator('[data-testid=viewer]').boundingBox();
const v = await p.evaluate(() => { const v = document.querySelector('[data-testid=viewer]'); return {s:+v.dataset.scale, tx:+v.dataset.tx, ty:+v.dataset.ty}; });
console.log(v);
// find the screenshot's brightest pixel block
const buf = await p.screenshot({ clip: { x: box.x, y: box.y, width: box.width, height: box.height } });
const res = await p.evaluate(async (b64) => { const img = new Image(); img.src='data:image/png;base64,'+b64; await img.decode(); const c=document.createElement('canvas'); c.width=img.width;c.height=img.height; const g=c.getContext('2d'); g.drawImage(img,0,0); const d=g.getImageData(0,0,c.width,c.height).data; let xs=[],ys=[]; for(let y=0;y<c.height;y++)for(let x=0;x<c.width;x++){const i=(y*c.width+x)*4; if(d[i+1]>=250&&d[i]<30&&d[i+2]<30){xs.push(x);ys.push(y);} } return {n:xs.length, minx:Math.min(...xs),maxx:Math.max(...xs),miny:Math.min(...ys),maxy:Math.max(...ys)}; }, buf.toString('base64'));
console.log(res);
const cx = (res.minx+res.maxx+1)/2, cy=(res.miny+res.maxy+1)/2;
console.log('peak centre image coords', (cx - v.tx)/v.s, (cy - v.ty)/v.s, 'box', box.x, box.y);
await b.close(); server.close();
