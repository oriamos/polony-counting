import { chromium } from 'playwright-core';
import { server } from '../mock/server.mjs';
await new Promise((r) => server.listen(0, '127.0.0.1', r));
const BASE = `http://127.0.0.1:${server.address().port}`;
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1500, height: 900 } });
p.on('console', m => console.log('console', m.text()));
await p.goto(BASE);
await p.click('[data-testid=analysis-demo]');
await p.waitForTimeout(800);
const box = await p.locator('[data-testid=viewer]').boundingBox();
const v = await p.evaluate(() => { const v = document.querySelector('[data-testid=viewer]'); return {s:+v.dataset.scale, tx:+v.dataset.tx, ty:+v.dataset.ty}; });
const sc = (x,y)=>({x: box.x+v.tx+v.s*x, y: box.y+v.ty+v.s*y});
const a=sc(100,100), c=sc(60,320);
await p.mouse.click(a.x,a.y);
console.log('sel1', await p.locator('[data-testid=inspector]').count());
await p.mouse.click(c.x,c.y,{modifiers:['Shift']});
console.log('inspector text', (await p.locator('[data-testid=inspector]').innerText()).slice(0,60));
await p.keyboard.press('m');
await p.waitForTimeout(400);
console.log((await p.locator('[data-testid=toast]').allInnerTexts()));
await p.screenshot({path:'e2e-artifacts/dbg.png'});
await b.close(); server.close();
